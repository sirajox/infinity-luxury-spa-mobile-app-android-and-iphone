/**
 * Generates packages/core/src/database.types.ts by introspecting the schema produced by the real
 * migrations. Output mirrors the shape of `supabase gen types typescript` so it can be swapped for the
 * CLI output once a Supabase project is linked:  supabase gen types typescript --local
 *
 * Run: npm run gen:types -w @infinity/db-tests
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createDb } from './helpers';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'packages', 'core', 'src', 'database.types.ts');

const scalar: Record<string, string> = {
  uuid: 'string', text: 'string', varchar: 'string', bpchar: 'string', citext: 'string', name: 'string',
  int2: 'number', int4: 'number', int8: 'number', numeric: 'number', float4: 'number', float8: 'number',
  bool: 'boolean', date: 'string', time: 'string', timestamp: 'string', timestamptz: 'string', interval: 'unknown',
  json: 'Json', jsonb: 'Json', tsvector: 'string', tstzrange: 'string', void: 'undefined', trigger: 'unknown',
};

function ts(typname: string, enums: Set<string>): string {
  const isArray = typname.startsWith('_');
  const base = isArray ? typname.slice(1) : typname;
  const t = enums.has(base) ? `Database["public"]["Enums"]["${base}"]` : scalar[base] ?? 'unknown';
  return isArray ? `${t}[]` : t;
}

const db = await createDb({ seed: false });
const enumsRes = await db.query<{ typname: string; labels: string[] }>(`
  select t.typname, array_agg(e.enumlabel order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`);
const enumNames = new Set(enumsRes.rows.map((r) => r.typname));

const cols = await db.query<{
  table_name: string; column_name: string; udt_name: string; is_nullable: string; column_default: string | null;
  is_generated: string; is_identity: string; table_type: string;
}>(`
  select c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default, c.is_generated, c.is_identity, t.table_type
  from information_schema.columns c join information_schema.tables t using (table_schema, table_name)
  where c.table_schema = 'public' order by c.table_name, c.ordinal_position`);

const byTable = new Map<string, typeof cols.rows>();
for (const c of cols.rows) byTable.set(c.table_name, [...(byTable.get(c.table_name) ?? []), c]);

const fns = await db.query<{
  proname: string; argnames: string[] | null; argtypes: string[]; argmodes: string[] | null; rettype: string; retset: boolean; nargdefaults: number;
}>(`
  select p.proname,
         p.proargnames as argnames,
         (select array_agg(format_type(t, null) order by ord) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality as u(t, ord)) as argtypes,
         p.proargmodes as argmodes,
         (select typname from pg_type where oid = p.prorettype) as rettype,
         p.proretset, p.pronargdefaults as nargdefaults
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f' and has_function_privilege('authenticated', p.oid, 'execute')
  order by p.proname`);

function pgFormatToTs(formatted: string): string {
  const isArray = formatted.endsWith('[]');
  const base = formatted.replace(/\[\]$/, '').replace(/^public\./, '').replace(/"/g, '').replace(/ with(out)? time zone/, (_m, w) => (w ? '' : 'tz'));
  const norm: Record<string, string> = {
    uuid: 'uuid', text: 'text', integer: 'int4', bigint: 'int8', boolean: 'bool', date: 'date', 'time': 'time',
    timestamptz: 'timestamptz', timestamp: 'timestamp', jsonb: 'jsonb', json: 'json', numeric: 'numeric', smallint: 'int2',
    'character varying': 'varchar',
  };
  const typname = norm[base] ?? base;
  const t = enumNames.has(typname) ? `Database["public"]["Enums"]["${typname}"]` : scalar[typname] ?? 'unknown';
  return isArray ? `${t}[]` : t;
}

let o = `// AUTO-GENERATED by supabase/tests/gen-types.ts from the migrations in supabase/migrations. Do not edit.
// Replace with \`supabase gen types typescript --local\` output once a Supabase project is linked.
/* eslint-disable */
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  __InternalSupabase: {
    PostgrestVersion: \"13.0.5\"
  }
  public: {
    Tables: {
`;
const renderTables = (type: 'BASE TABLE' | 'VIEW') => {
  let s = '';
  for (const [table, columns] of byTable) {
    if (columns[0]!.table_type !== type) continue;
    const row = columns.map((c) => `          ${c.column_name}: ${ts(c.udt_name, enumNames)}${c.is_nullable === 'YES' ? ' | null' : ''}`).join('\n');
    if (type === 'VIEW') {
      s += `      ${table}: {\n        Row: {\n${row}\n        }\n        Relationships: []\n      }\n`;
      continue;
    }
    const writable = columns.filter((c) => c.is_generated !== 'ALWAYS');
    const ins = writable.map((c) => {
      const optional = c.is_nullable === 'YES' || c.column_default !== null || c.is_identity === 'YES';
      return `          ${c.column_name}${optional ? '?' : ''}: ${ts(c.udt_name, enumNames)}${c.is_nullable === 'YES' ? ' | null' : ''}`;
    }).join('\n');
    const upd = writable.map((c) => `          ${c.column_name}?: ${ts(c.udt_name, enumNames)}${c.is_nullable === 'YES' ? ' | null' : ''}`).join('\n');
    s += `      ${table}: {\n        Row: {\n${row}\n        }\n        Insert: {\n${ins}\n        }\n        Update: {\n${upd}\n        }\n        Relationships: []\n      }\n`;
  }
  return s;
};
o += renderTables('BASE TABLE');
o += `    }\n    Views: {\n${renderTables('VIEW')}    }\n    Functions: {\n`;
for (const f of fns.rows) {
  const names = f.argnames ?? [];
  const modes = f.argmodes ?? [];
  const inArgs: string[] = [];
  const tableCols: string[] = [];
  (f.argtypes ?? []).forEach((t, i) => {
    const mode = modes[i] ?? 'i';
    if (mode === 'i' || mode === 'b') {
      const defaultsStart = (f.argtypes.length - modes.filter((m) => m === 't').length) - f.nargdefaults;
      inArgs.push(`${names[i] ?? `arg${i}`}${i >= defaultsStart ? '?' : ''}: ${pgFormatToTs(t)} | null`);
    } else if (mode === 't') {
      tableCols.push(`${names[i]}: ${pgFormatToTs(t)}`);
    }
  });
  const ret = tableCols.length ? `{ ${tableCols.join('; ')} }[]` : f.retset ? `${ts(f.rettype, enumNames)}[]` : ts(f.rettype, enumNames);
  const isRow = byTable.has(f.rettype) && !tableCols.length;
  const retType = isRow ? `Database["public"]["Tables"]["${f.rettype}"]["Row"]` : ret;
  o += `      ${f.proname}: { Args: ${inArgs.length ? `{ ${inArgs.join('; ')} }` : 'Record<PropertyKey, never>'}; Returns: ${retType} }\n`;
}
o += `    }\n    Enums: {\n`;
for (const e of enumsRes.rows) o += `      ${e.typname}: ${e.labels.map((l) => JSON.stringify(l)).join(' | ')}\n`;
o += `    }\n    CompositeTypes: { [_ in never]: never }\n  }\n}\n\n`;
o += `type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;
writeFileSync(out, o);
console.log(`wrote ${out}: ${byTable.size} relations, ${fns.rows.length} functions, ${enumsRes.rows.length} enums`);
await db.close();
